#!/usr/bin/env python3
"""Builds iso_cruise_app/Resources/SafetyTerms.txt for the on-device content filter.

Sources (downloaded into a working directory, see README "Safety filter"):
  * obscenity English preset (MIT, (c) Joseph Liu; words derived from `cuss`, MIT, (c) Titus Wormer)
    https://github.com/jo3-l/obscenity/blob/main/src/preset/english.ts
  * LDNOOBW English list (CC-BY-4.0, Shutterstock) -- modified: kid-safe exclusions below
    https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words

Output format, one entry per line:
  P <pattern>   blocked pattern. `|` = word boundary, `[x]` = optional, `?` = any one character.
                Patterns are written against *transformed* text (see ContentFilter.swift).
  A <term>      allowlisted term; a blocked match fully inside an allowlisted term is ignored.

Usage: python3 Tools/build_safety_terms.py <dir containing obscenity-english.ts and ldnoobw-en.txt>
"""
import pathlib
import re
import sys

# LDNOOBW entries that are common, innocent words or phrases in a kids' chat/game app
# (false positives outweigh the benefit). Mild terms like "butt" stay blocked.
LDNOOBW_EXCLUDE = {
    "suck", "sucks", "domination", "escort", "eunuch", "rectum", "scat", "snatch", "swinger",
    "twinkie", "twink", "xx", "sadism", "mong", "poof", "skeet", "shrimping", "bastinado",
    "santorum", "hardcore", "fingering", "big black", "tied up", "tight white", "hot chick",
    "girl on", "taste my", "tongue in a", "tainted love", "dirty pillows", "jelly donut",
    "huge fat", "how to kill", "how to murder", "wrapping men", "beaver cleaver",
    "chocolate rosebuds", "ball kicking", "hard core", "violet wand", "pleasure chest",
    "sultry women", "bimbos", "voyeur", "figging",
}

# Extra innocent words that the patterns would otherwise catch.
EXTRA_ALLOW = [
    "assault", "assort", "asst", "cumin", "cockpit", "rapeseed", "retardant", "retardation",
    "shiitake", "scunthorpe", "penistone", "cockatoo", "cockatiel", "cockroach", "cocktail",
    "hancock", "peacock", "dickens", "dickson", "matsui", "therapist", "grape", "drape",
    "scrape", "skyscraper", "arsenal", "canal", "analysis", "analyst", "titanic", "titan",
    "title", "constitution", "sextant", "sextet", "sussex", "essex", "middlesex",
    "pussycat", "pussywillow", "spice", "spicy", "hello", "shell", "seashell",
]

# Kid-safety additions not covered by the sources.
EXTRA_PATTERNS = [
    "|nudes|", "|nudez|", "|send nudes", "onlyfans", "|sext", "|thot|", "|wtf|", "|stfu|",
    "|milf", "|dtf|", "|nsfw", "|hoe|", "|hoes|", "|damn|", "|dammit|", "|goddam",
    "|bullshit", "|horny", "|sexting", "|kys|", "|kill yourself", "|killyourself",
    "phuck", "fvck", "|fck", "|fuq", "|sht|", "|azz|", "|biatch", "|beetch",
]

# Mirrors ContentFilter's collapse step: runs of the same character are collapsed to one,
# except these letters, which keep up to two (so "ass" stays distinct from "as").
KEEP_DOUBLE = set("beolsg")


def collapse(text: str) -> str:
    out = []
    for ch in text:
        if out and out[-1] == ch:
            limit = 2 if ch in KEEP_DOUBLE else 1
            run = 1
            i = len(out) - 1
            while i >= 0 and out[i] == ch:
                run += 1
                i -= 1
            if run > limit:
                continue
        out.append(ch)
    return "".join(out)


def escape(term: str) -> str:
    # Escape characters that have meaning in our pattern syntax.
    return re.sub(r"([|\[\]?])", r"\\\1", term)


def main() -> None:
    src = pathlib.Path(sys.argv[1])
    obscenity = (src / "obscenity-english.ts").read_text()
    ldnoobw = (src / "ldnoobw-en.txt").read_text().splitlines()

    patterns: list[str] = []
    allow: list[str] = []

    for match in re.finditer(r"pattern`([^`]*)`|addWhitelistedTerm\('([^']*)'\)", obscenity):
        pattern, allowed = match.groups()
        if pattern is not None:
            patterns.append(pattern)
        elif allowed is not None:
            allow.append(allowed)

    # The first `pattern` in the file is a doc-comment example (|balls|); drop it.
    if patterns and patterns[0] == "|balls|":
        patterns.pop(0)

    for raw in ldnoobw:
        term = raw.strip().lower()
        if not term or term in LDNOOBW_EXCLUDE:
            continue
        patterns.append("|" + escape(collapse(term)) + "|")

    patterns.extend(EXTRA_PATTERNS)
    allow.extend(EXTRA_ALLOW)

    def dedupe(items):
        seen, result = set(), []
        for item in items:
            if item not in seen:
                seen.add(item)
                result.append(item)
        return result

    lines = [
        "# CruiseLAN safety filter terms. Generated by Tools/build_safety_terms.py -- do not edit by hand.",
        "# Contains material from: obscenity (MIT, (c) 2025 Joseph Liu; derived from cuss, MIT, (c) 2016 Titus Wormer)",
        "# and LDNOOBW (CC-BY-4.0, Shutterstock), modified with kid-safe exclusions and additions.",
    ]
    lines += ["P " + p for p in dedupe(patterns)]
    lines += ["A " + collapse(a.lower()) for a in dedupe(allow)]

    out = pathlib.Path(__file__).resolve().parent.parent / "iso_cruise_app" / "Resources" / "SafetyTerms.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out} ({len(dedupe(patterns))} patterns, {len(dedupe(allow))} allowlisted terms)")


if __name__ == "__main__":
    main()
