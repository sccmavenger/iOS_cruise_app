import WebSocket from "ws";
const BASE = process.env.BASE ?? "https://cruiselan-games.dguilloryjr.workers.dev";
const post = async (p, b) => (await fetch(BASE + p, { method: "POST", body: JSON.stringify(b) })).json();
const a = await post("/v1/rooms", { game: "ticTacToe", nickname: "A" }), b = await post(`/v1/rooms/${a.code}/join`, { nickname: "B" });
const t0 = Date.now(), T = () => `+${((Date.now() - t0) / 1000).toFixed(1)}s`;
const open = (t, n) => new Promise((r) => { const ws = new WebSocket(`${BASE.replace(/^http/, "ws")}/v1/rooms/${a.code}/socket`, { headers: { Authorization: `Bearer ${t}` } });
  ws.on("open", () => { ws.send(JSON.stringify({ type: "resume" })); r(ws); });
  ws.on("message", (d) => { const m = JSON.parse(d); if (m.type === "roster") console.log(T(), n, "roster", m.players.map((p) => p.nickname + (p.connected ? "" : "(away)")).join(",")); });
  ws.on("close", (c) => console.log(T(), n, "closed", c)); });
const wa = await open(a.token, "A"), wb = await open(b.token, "B");
await new Promise((s) => setTimeout(s, 2000));
console.log(T(), "A drops abruptly (TCP reset)");
wa._socket.destroy();
await new Promise((s) => setTimeout(s, 2000));
console.log(T(), "A reconnects");
const wa2 = await open(a.token, "A2");
await new Promise((s) => setTimeout(s, 5000));
console.log(T(), "open now: A2", wa2.readyState === 1, "B", wb.readyState === 1);
process.exit(0);
